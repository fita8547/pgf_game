// Generates lib/src/content/catalog.g.dart from rps_assets/catalog.json.
// Re-run after the assets are rebuilt:
//   dart run tool/gen_catalog.dart ../rps_assets/catalog.json
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final src = args.isEmpty ? '../rps_assets/catalog.json' : args[0];
  final c = jsonDecode(File(src).readAsStringSync()) as Map<String, dynamic>;
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_catalog.dart from rps_assets/catalog.json. Do not edit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'catalog_types.dart';")
    ..writeln();

  String s(Object? v) => jsonEncode(v ?? '').replaceAll(r'$', r'\$');
  String l(List v) => '[${v.map((e) => (e as num).toDouble()).join(', ')}]';

  const roles = {'디펜서': 'Role.defender', '어택': 'Role.attack', '힐러': 'Role.healer', '컨트롤러': 'Role.controller'};
  const keys = {'Q': 'SkillKey.q', 'E': 'SkillKey.e', 'Shift': 'SkillKey.shift', '궁': 'SkillKey.ult'};

  b.writeln('const List<CharacterInfo> characterInfos = [');
  for (final ch in c['characters'] as List) {
    b.writeln('  CharacterInfo(');
    b.writeln('    id: ${s(ch['id'])},');
    b.writeln('    name: ${s(ch['name'])},');
    b.writeln('    role: ${roles[ch['role']] ?? (throw 'unknown role ${ch['role']}')},');
    b.writeln('    race: ${s(ch['race'])},');
    b.writeln('    sex: ${s(ch['sex'])},');
    b.writeln('    file: ${s(ch['file'])},');
    b.writeln('    fpArms: ${s(ch['fp_arms'])},');
    b.writeln('    skills: [');
    for (final sk in ch['skills'] as List) {
      final cd = sk['cd'] as String;
      final secs = RegExp(r'^(\d+(?:\.\d+)?)초').firstMatch(cd)?.group(1);
      final kind = switch (cd) {
        '궁극기' => 'CooldownKind.ultimate',
        '유지형' => 'CooldownKind.sustain',
        '전환' || '대상 전환' => 'CooldownKind.toggle',
        '충전형' => 'CooldownKind.charges',
        '재설치' => 'CooldownKind.redeploy',
        _ when cd.contains('/충전') => 'CooldownKind.charges',
        _ => 'CooldownKind.cooldown',
      };
      b.writeln('      SkillInfo(id: ${s(sk['id'])}, key: ${keys[sk['key']]}, name: ${s(sk['name'])}, '
          'desc: ${s(sk['desc'])}, cdText: ${s(cd)}, cooldown: ${secs ?? 0}, kind: $kind, file: ${s(sk['file'])}),');
    }
    b.writeln('    ],');
    b.writeln('  ),');
  }
  b.writeln('];');
  b.writeln();

  b.writeln('const List<GunInfo> gunInfos = [');
  for (final g in c['guns'] as List) {
    final a = g['ads'] as Map;
    b.writeln('  GunInfo(id: ${s(g['id'])}, name: ${s(g['name'])}, gunClass: ${s(g['class'])}, file: ${s(g['file'])}, '
        'fpRig: ${s(g['fp'])}, adsHold: ${l(a['hold'] as List)}, adsSight: ${l(a['sight'] as List)}, '
        'adsFov: ${(a['ads_fov'] as num).toDouble()}, adsEye: ${(a['eye'] as num).toDouble()}, '
        'scope: ${a['scope']}, overlay: ${a['overlay']}),');
  }
  b.writeln('];');
  b.writeln();

  b.writeln('const List<FxInfo> fxInfos = [');
  for (final f in c['fx'] as List) {
    b.writeln('  FxInfo(id: ${s(f['id'])}, name: ${s(f['name'])}, file: ${s(f['file'])}, anim: ${s(f['anim'])}),');
  }
  b.writeln('];');
  b.writeln();

  b.writeln('/// First-person camera presets for map previews, by map id: (pos, look).');
  b.writeln('const Map<String, (List<double>, List<double>)> mapPreviewCams = {');
  for (final m in c['maps'] as List) {
    final cam = m['fp_cam'] as Map;
    b.writeln('  ${s(m['id'])}: (${l(cam['pos'] as List)}, ${l(cam['look'] as List)}),');
  }
  b.writeln('};');

  final out = File('lib/src/content/catalog.g.dart');
  out.writeAsStringSync(b.toString());
  print('wrote ${out.path}');
}
